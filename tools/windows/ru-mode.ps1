# Переключатель маршрута российских ресурсов (с Win10 через SSH на роутер). Не требует прав администратора.
#   .\ru-mode.ps1 status       - показать текущий режим
#   .\ru-mode.ps1 direct       - все российские ресурсы напрямую (по умолчанию)
#   .\ru-mode.ps1 proxy        - все российские ресурсы через пул (включайте, если оператор при белых списках режет российские адреса)
#   .\ru-mode.ps1 node ID      - все российские ресурсы через конкретный узел PassWall2
# Двойной щелчок по ru-direct.cmd / ru-proxy.cmd - то же самое одной кнопкой. Действует на прокси 8080/1080 и на системный трафик через шлюз.
# Смена режима перезапускает PassWall2 (~10 с, текущие соединения на миг обрываются). Порты 1081/8081 не затрагиваются.
param([ValidateSet('status', 'direct', 'proxy', 'node')][string]$Mode = 'status', [string]$NodeId = '')
if ($Mode -eq 'node' -and -not $NodeId) { Write-Host 'Укажите ID узла: .\ru-mode.ps1 node <ID>'; exit 1 }
ssh openwrt "pw2-ru-mode $Mode $NodeId"
