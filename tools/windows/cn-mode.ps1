# Переключатель маршрута китайского трафика (с Win10 через SSH на роутер). Не требует прав администратора.
#   .\cn-mode.ps1 status     - режим, текущее правило, доступен ли Китай напрямую прямо сейчас
#   .\cn-mode.ps1 auto       - напрямую, пока Китай доступен; если недоступен - через пул (автоматически)
#   .\cn-mode.ps1 direct     - всегда напрямую
#   .\cn-mode.ps1 proxy      - всегда через пул (включайте, если Китай напрямую не открывается)
# Действует на прокси 8080/1080 и на системный трафик через шлюз. Смена режима перезапускает PassWall2 (~10 с).
param([ValidateSet('status', 'auto', 'direct', 'proxy')][string]$Mode = 'status')
ssh openwrt "pw2-cn-mode $Mode"
